ROLES = ('R_LUSU', 'R_ZHUGE', 'R_CAO')


def line(speaker, text):
    return {'speaker': speaker, 'text': text}


def role_scene(description, *lines):
    return {'description': description, 'lines': [line(*item) for item in lines]}


def scene(title, act, location, stage, description, lusu, zhuge, cao):
    return dict(title=title, act=act, location=location, stage=stage,
                description=description, roles=dict(zip(ROLES, (lusu, zhuge, cao))))


def response(lusu, zhuge, cao):
    return dict(zip(ROLES, (line('诸葛亮', lusu), line('鲁肃', zhuge), line('哨卒', cao))))


def action(label, description, answers, choices=None, role_overrides=None):
    value = dict(label=label, description=description, response=response(*answers))
    if choices:
        value['choices'] = choices
    if role_overrides:
        value['role_overrides'] = role_overrides
    return value


def ending(title, description, lines, closing_shot):
    return dict(title=title, description=description,
                lines=[line(*item) for item in lines], closing_shot=closing_shot)


